package ejemploSwitch1;

public class EjemploSwitch1 {

	public static void main(String[] args) {
		Integer x = 2;
		switch (x) {
		case 1:
			System.out.println("Viva");
			break;
		case 2:
			System.out.println("Er beti weno");
			break;
		case 3:
			System.out.println("Manque pierda");
			break;
		default:
			System.out.println("Holaaaaaaaaaaaa");
			;
		}
	}

}
